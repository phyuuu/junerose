create or replace function public.adjust_product_stock(
  target_variant_id bigint,
  adjustment_amount integer
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  updated_variant_id bigint;
begin
  if not coalesce(public.current_user_is_active_staff(), false) then
    raise exception using
      errcode = '42501',
      message = 'Active staff access is required.';
  end if;

  if adjustment_amount = 0 then
    raise exception 'Adjustment cannot be zero.';
  end if;

  update public.product_variants
  set quantity = quantity + adjustment_amount
  where id = target_variant_id
    and quantity + adjustment_amount >= 0
  returning id into updated_variant_id;

  if not found then
    raise exception 'Stock cannot be negative or the variant was not found.';
  end if;

  insert into public.inventory_adjustments (
    product_variant_id,
    quantity_change,
    changed_by
  )
  values (
    updated_variant_id,
    adjustment_amount,
    auth.uid()
  );
end;
$$;

