create or replace function public.create_product_with_variants(
  product_code text,
  product_slug text,
  product_name text,
  product_description text,
  product_price_mmk bigint,
  product_category text,
  product_availability text,
  product_is_visible boolean,
  product_variants jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_product_id bigint;
  submitted_variant jsonb;
  selected_size public.sizes%rowtype;
  selected_color public.colors%rowtype;
begin
  if not coalesce(public.current_user_is_active_staff(), false) then
    raise exception using
      errcode = '42501',
      message = 'Active staff access is required.';
  end if;

  insert into public.products (
    code,
    slug,
    name,
    description,
    price_mmk,
    category,
    availability,
    is_visible
  )
  values (
    trim(product_code),
    trim(product_slug),
    trim(product_name),
    trim(product_description),
    product_price_mmk,
    product_category,
    product_availability,
    product_is_visible
  )
  returning id into new_product_id;

  if jsonb_typeof(coalesce(product_variants, '[]'::jsonb)) <> 'array' then
    raise exception 'Product variants must be an array.';
  end if;

  for submitted_variant in
    select value
    from jsonb_array_elements(coalesce(product_variants, '[]'::jsonb))
  loop
    select * into selected_size
    from public.sizes
    where id = (submitted_variant->>'sizeId')::bigint
      and is_active = true;

    select * into selected_color
    from public.colors
    where id = (submitted_variant->>'colorId')::bigint
      and is_active = true;

    if selected_size.id is null or selected_color.id is null then
      raise exception 'Select valid product options.';
    end if;

    insert into public.product_variants (
      product_id,
      size,
      color,
      size_id,
      color_id,
      quantity
    )
    values (
      new_product_id,
      selected_size.name,
      selected_color.name,
      selected_size.id,
      selected_color.id,
      (submitted_variant->>'quantity')::integer
    );
  end loop;

  return new_product_id;
end;
$$;

