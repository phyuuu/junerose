create function public.create_product_with_variants(
  product_code text,
  product_slug text,
  product_name text,
  product_description text,
  product_price_mmk bigint,
  product_department_id bigint,
  product_type_id bigint,
  product_material_ids bigint[],
  product_availability text,
  product_is_visible boolean,
  product_variants jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_product_id bigint;
  submitted_variant jsonb;
  selected_size public.sizes%rowtype;
  selected_color public.colors%rowtype;
  requested_material_count integer;
  valid_material_count integer;
begin
  if not coalesce(public.current_user_is_active_staff(), false) then
    raise exception using errcode = '42501', message = 'Active staff access is required.';
  end if;

  if not exists (
    select 1 from public.departments
    where id = product_department_id and is_active = true
  ) or not exists (
    select 1 from public.product_types
    where id = product_type_id and is_active = true
  ) then
    raise exception 'Select a valid department and product type.';
  end if;

  select count(distinct requested.id) into requested_material_count
  from unnest(coalesce(product_material_ids, array[]::bigint[])) as requested(id);

  select count(*) into valid_material_count
  from public.materials
  where id = any(coalesce(product_material_ids, array[]::bigint[]))
    and is_active = true;

  if requested_material_count <> valid_material_count then
    raise exception 'Select valid materials.';
  end if;

  insert into public.products (
    code, slug, name, description, price_mmk, department_id,
    product_type_id, availability, is_visible
  ) values (
    trim(product_code), trim(product_slug), trim(product_name),
    trim(product_description), product_price_mmk, product_department_id,
    product_type_id, product_availability, product_is_visible
  ) returning id into new_product_id;

  insert into public.product_materials (product_id, material_id)
  select new_product_id, material_id
  from (
    select distinct unnest(coalesce(product_material_ids, array[]::bigint[])) as material_id
  ) requested;

  if jsonb_typeof(coalesce(product_variants, '[]'::jsonb)) <> 'array' then
    raise exception 'Product variants must be an array.';
  end if;

  for submitted_variant in
    select value from jsonb_array_elements(coalesce(product_variants, '[]'::jsonb))
  loop
    select * into selected_size from public.sizes
    where id = (submitted_variant->>'sizeId')::bigint and is_active = true;

    select * into selected_color from public.colors
    where id = (submitted_variant->>'colorId')::bigint and is_active = true;

    if selected_size.id is null or selected_color.id is null then
      raise exception 'Select valid product options.';
    end if;

    insert into public.product_variants (
      product_id, size, color, size_id, color_id, quantity
    ) values (
      new_product_id, selected_size.name, selected_color.name,
      selected_size.id, selected_color.id,
      (submitted_variant->>'quantity')::integer
    );
  end loop;

  return new_product_id;
end;
$$;

create function public.update_product_info(
  target_product_id bigint,
  new_name text,
  new_description text,
  new_price_mmk bigint,
  new_department_id bigint,
  new_product_type_id bigint,
  new_material_ids bigint[],
  new_availability text,
  new_is_visible boolean
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  requested_material_count integer;
  valid_material_count integer;
begin
  if not coalesce(public.current_user_is_active_staff(), false) then
    raise exception using errcode = '42501', message = 'Active staff access is required.';
  end if;

  if not exists (
    select 1 from public.departments
    where id = new_department_id and is_active = true
  ) or not exists (
    select 1 from public.product_types
    where id = new_product_type_id and is_active = true
  ) then
    raise exception 'Select a valid department and product type.';
  end if;

  select count(distinct requested.id) into requested_material_count
  from unnest(coalesce(new_material_ids, array[]::bigint[])) as requested(id);

  select count(*) into valid_material_count
  from public.materials
  where id = any(coalesce(new_material_ids, array[]::bigint[]))
    and (
      is_active = true
      or exists (
        select 1 from public.product_materials
        where product_id = target_product_id
          and material_id = materials.id
      )
    );

  if requested_material_count <> valid_material_count then
    raise exception 'Select valid materials.';
  end if;

  update public.products set
    name = trim(new_name),
    description = trim(new_description),
    price_mmk = new_price_mmk,
    department_id = new_department_id,
    product_type_id = new_product_type_id,
    availability = new_availability,
    is_visible = new_is_visible
  where id = target_product_id and deleted_at is null;

  if not found then
    raise exception 'Product not found.';
  end if;

  delete from public.product_materials where product_id = target_product_id;

  insert into public.product_materials (product_id, material_id)
  select target_product_id, material_id
  from (
    select distinct unnest(coalesce(new_material_ids, array[]::bigint[])) as material_id
  ) requested;
end;
$$;

