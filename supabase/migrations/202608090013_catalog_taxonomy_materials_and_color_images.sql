-- Separate customer-facing catalog taxonomy, add reusable materials, and let
-- product photos optionally belong to a product color.

begin;

create table public.departments (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  sort_order integer null,
  is_active boolean not null default true,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

create unique index departments_name_lower_idx
on public.departments (lower(name));

create table public.product_types (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  sort_order integer null,
  is_active boolean not null default true,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

create unique index product_types_name_lower_idx
on public.product_types (lower(name));

create table public.materials (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  sort_order integer null,
  is_active boolean not null default true,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

create unique index materials_name_lower_idx
on public.materials (lower(name));

