create function public.get_public_products()
returns table (
  id bigint,
  slug text,
  name text,
  description text,
  price_mmk bigint,
  department text,
  department_slug text,
  product_type text,
  product_type_slug text,
  availability text
)
language sql
stable
security definer
set search_path = public
as $$
  select
    products.id::bigint,
    products.slug::text,
    products.name::text,
    products.description::text,
    products.price_mmk::bigint,
    departments.name::text,
    departments.slug::text,
    product_types.name::text,
    product_types.slug::text,
    case
      when coalesce(stock.total_quantity, 0) <= 0 then 'Sold out'
      when products.availability = 'Ask staff' then 'Ask staff'
      when products.availability = 'Low stock'
        or stock.total_quantity <= 5 then 'Low stock'
      else 'Available'
    end::text
  from public.products
  join public.departments on departments.id = products.department_id
  join public.product_types on product_types.id = products.product_type_id
  left join lateral (
    select sum(product_variants.quantity) as total_quantity
    from public.product_variants
    where product_variants.product_id = products.id
  ) as stock on true
  where products.is_visible = true
    and products.deleted_at is null
    and departments.is_active = true
    and product_types.is_active = true
  order by products.id;
$$;

create function public.get_public_product_images()
returns table (
  image_id bigint,
  product_id bigint,
  image_url text,
  display_order integer,
  color_id bigint,
  color_name text
)
language sql
stable
security definer
set search_path = public
as $$
  select
    product_images.id::bigint,
    product_images.product_id::bigint,
    product_images.image_url::text,
    product_images.display_order::integer,
    product_images.color_id::bigint,
    colors.name::text
  from public.product_images
  join public.products on products.id = product_images.product_id
  left join public.colors on colors.id = product_images.color_id
  where products.is_visible = true
    and products.deleted_at is null
  order by product_images.product_id, product_images.display_order, product_images.id;
$$;

create function public.get_public_product_materials()
returns table (
  product_id bigint,
  material_id bigint,
  material_name text,
  material_slug text,
  sort_order integer
)
language sql
stable
security definer
set search_path = public
as $$
  select
    product_materials.product_id::bigint,
    materials.id::bigint,
    materials.name::text,
    materials.slug::text,
    materials.sort_order::integer
  from public.product_materials
  join public.materials on materials.id = product_materials.material_id
  join public.products on products.id = product_materials.product_id
  where products.is_visible = true
    and products.deleted_at is null
    and materials.is_active = true
  order by product_materials.product_id, materials.sort_order, materials.id;
$$;

